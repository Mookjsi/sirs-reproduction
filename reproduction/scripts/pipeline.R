# Entrypoint. Do not source this file during static validation.
file_arg <- grep("^--file=",commandArgs(),value=TRUE)
REPRO_ROOT <- normalizePath(file.path(dirname(sub("^--file=","",file_arg)),".."))
source(file.path(REPRO_ROOT,"configs/defaults.R"))
source(file.path(REPRO_ROOT,"scripts/pipeline_common.R"))
source(file.path(REPRO_ROOT,"scripts/pipeline_actions.R"))
source(file.path(REPRO_ROOT,"diagnostics/posterior.R"))
source(file.path(REPRO_ROOT,"figures/source_adapter.R"))
source(file.path(REPRO_ROOT,"figures/pipeline_figures.R"))
source(file.path(REPRO_ROOT,"simulations/original_counterfactuals.R"))
o <- parse_options(commandArgs(trailingOnly=TRUE),
                   extra_allowed=c("fits","simulations","target","figure","experiment"))
phase4_commands <- c("check-figures","figure","supplement","counterfactual")
stopifnot(o$command %in% c("prepare","run","run-all","extract","diagnose","plots","ppc",phase4_commands))
cpus <- positive_int(if(is.null(o$cpus)) "4" else o$cpus,"cpus")
options(mc.cores=cpus)
Sys.setenv(MAKEFLAGS="-j1",OMP_NUM_THREADS="1",OPENBLAS_NUM_THREADS="1",
           MKL_NUM_THREADS="1",RCPP_PARALLEL_NUM_THREADS="1",STAN_NUM_THREADS="1")
library(rstan)
stopifnot(packageVersion("rstan")=="2.32.6",packageVersion("StanHeaders")=="2.32.6")
RcppParallel::setThreadOptions(numThreads=1)
registry <- read.csv(file.path(REPRO_ROOT,"configs/regions.csv"),stringsAsFactors=FALSE)
src <- if(o$command %in% phase4_commands) file.path(REPRO_ROOT,"source",source_commit) else assert_sources(REPRO_ROOT)
if(o$command=="prepare") prepare_data(o,REPRO_ROOT,src,registry)
if(o$command %in% c("run","run-all")) run_regions(o,REPRO_ROOT,src,registry)
if(o$command %in% c("extract","diagnose","plots","ppc")) postprocess(o,REPRO_ROOT)
if(o$command %in% phase4_commands) phase4_dispatch(o,REPRO_ROOT,src,registry)
